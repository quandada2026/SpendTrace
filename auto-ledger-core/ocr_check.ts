// 临时验证脚本：模拟真实 OCR 噪声，检查金额/商户/时间/分类提取的鲁棒性
import { parseScreenshot } from './src/parse/index.js';
import { categorize } from './src/categorize/index.js';
import type { OcrResult } from './src/types.js';

function ocr(text: string): OcrResult {
  return { text, blocks: [], engine: 'test' };
}

const cases: Array<[string, string]> = [
  // 微信：规范
  ['微信-规范', '微信支付\n支付成功\n收款方备注：星巴克咖啡(天河城店)\n付款方式：零钱\n金额 ¥32.00\n2026-08-18 09:30:12'],
  // 微信：OCR 把"备注"识别成"备住/备让/备庄"等错字
  ['微信-备注错字', '微信支付\n支付成功\n收款方备住：星巴克咖啡(天河城店)\n付款方式：零钱\n金额 ¥32.00'],
  // 微信：金额标签缺失，只有 ¥
  ['微信-无金额标签', '微信支付\n支付成功\n收款方备注：星巴克咖啡(天河城店)\n付款方式：零钱\n¥32.00'],
  // 支付宝：全角￥、负号
  ['支付宝-全角', '支付宝\n支付成功\n商家：麦当劳\n付款方式：花呗\n－￥25.50\n2026-08-18 12:01:05'],
  // 银行：金额带空格、千分位
  ['银行-空格千分位', '招商银行\n交易成功\n交易金额 ¥ 1,200.00\n对方户名：某某科技有限公司\n2026/08/18 18:22:33'],
  // 云闪付/其他：商户标签是"商户"或"收款方"
  ['云闪付-商户', '云闪付\n支付成功\n商户：全家便利店\n实付金额 ¥8.50\n2026-08-18 08:00:00'],
  // 京东/电商：订单金额
  ['电商-订单金额', '京东支付\n支付成功\n订单金额：¥199.00\n商户：京东商城自营'],
  // OCR 数字错乱：金额 32.00 识别成 32.0O（字母O）——应尽量兜底
  ['微信-O当0', '微信支付\n支付成功\n收款方备注：星巴克\n金额 ¥32.0O'],
  // 严重失真：¥ 被识别成 4、数字周围夹字母（来自用户实测的真实 OCR 输出）
  ['严重失真-¥→4夹字母', '14:26 @0\n三记录、2026年8月、1月支出 24.00 o\n1月收入 0.00 记录明细 今天 |统计 1月结余 -¥24.00 资产管理|看清资金流动，助力财富增值 餐饮 14:23 |午饭24 o0.60 5G 记查账都找我 任何事都能问我 KB/s tl ti 59 总账本v |智能预算 |点击定制方案 + |支 24.00 |收 0.00 胖哒:恭喜完成第一笔记账!坚持记账21天就能养成好习惯。 - 424.00 +'],
  // ¥ 后无空格 + 数字周围乱码
  ['金额标签后空格', '金额 ¥ 24.00 餐饮 午饭'],
  // 纯数字无 ¥ 符号
  ['无¥纯数字', '支付成功 餐饮 午饭 24.00 余额 1000.00'],
];

let ok = 0;
for (const [name, text] of cases) {
  const p = parseScreenshot(ocr(text));
  const cat = categorize(p.merchant, p.rawText);
  const flag = p.amount != null ? 'OK ' : 'FAIL';
  if (p.amount != null) ok++;
  console.log(
    `${flag} [${name}]\n   金额=${p.amount ?? '未识别!'} 商户=${p.merchant ?? '未识别'} 分类=${cat} 平台=${p.platform} needsReview=${p.needsReview}`,
  );
}
console.log(`\n金额识别成功 ${ok}/${cases.length}`);
